"""Export registry cards as a LiteLLM ``agents:`` config block.

Keeping an agent in two places is the main operational cost of the gateway
routing mode. This script makes the registry authoritative and regenerates the
LiteLLM side, so drift becomes visible in a diff.

    python scripts/export_litellm_agents.py \\
        --base-url http://localhost:8080 \\
        --user-id admin --roles platform-admin \\
        --out litellm/agents.generated.yaml
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import httpx


def fetch_cards(base_url: str, *, user_id: str, roles: str, environment: str | None) -> list[dict[str, Any]]:
    headers = {"X-User-Id": user_id, "X-User-Roles": roles}
    params = {"status": "active", "limit": 500}
    if environment:
        params["environment"] = environment
    response = httpx.get(f"{base_url.rstrip('/')}/v1/agents", headers=headers, params=params, timeout=30)
    response.raise_for_status()
    return response.json()["items"]


def to_litellm_agent(card: dict[str, Any]) -> dict[str, Any]:
    metadata = card.get("metadata") or {}
    agent_name = str(metadata.get("litellm_agent_name") or card["agent_id"])
    protocol_version = str(metadata.get("litellm_protocol_version") or "0.3")
    skills = [
        {
            "id": capability.lower().replace(" ", "-"),
            "name": capability,
            "description": card.get("description", ""),
            "tags": list(card.get("tags") or []),
            "examples": list(card.get("examples") or [])[:3],
        }
        for capability in card.get("capabilities") or []
    ]
    return {
        "agent_name": agent_name,
        "agent_card_params": {
            "name": card["name"],
            "description": card["description"],
            "url": card["endpoint"],
            "version": card["version"],
            "protocolVersion": protocol_version,
            "capabilities": {"streaming": False},
            "skills": skills,
        },
        "litellm_params": {"api_key": "os.environ/ALSTOM_AO_AGENT_KEY"},
    }


def to_yaml(agents: list[dict[str, Any]]) -> str:
    try:
        import yaml
    except ModuleNotFoundError:  # pragma: no cover - optional convenience
        return "# pip install pyyaml to render YAML\n" + json.dumps({"agents": agents}, indent=2)

    return yaml.safe_dump(
        {"agents": agents},
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-url", default="http://localhost:8080")
    parser.add_argument("--user-id", default="admin")
    parser.add_argument("--roles", default="platform-admin")
    parser.add_argument("--environment", default=None)
    parser.add_argument("--out", default=None, help="write to a file instead of stdout")
    args = parser.parse_args(argv)

    try:
        cards = fetch_cards(args.base_url, user_id=args.user_id, roles=args.roles, environment=args.environment)
    except httpx.HTTPError as exc:
        print(f"Could not read the registry at {args.base_url}: {exc}", file=sys.stderr)
        return 1

    agents = [to_litellm_agent(card) for card in cards]
    rendered = (
        "# Generated by scripts/export_litellm_agents.py - edit the registry, then re-run.\n" + to_yaml(agents)
    )
    if args.out:
        Path(args.out).write_text(rendered, encoding="utf-8")
        print(f"Wrote {len(agents)} agent(s) to {args.out}")
    else:
        print(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
